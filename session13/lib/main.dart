import 'package:firebase_core/firebase_core.dart'; // NEW
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'Controllers/app_controllers.dart';
import 'Views/TaskList_page.dart';
import 'Views/home_page.dart';
import 'firebase_options.dart'; // NEW: generated by flutterfire configure

// CHANGED: main() is now `async`, because we must WAIT for Firebase before
// using it.
void main() async {
  // NEW: needed whenever we `await` something before runApp().
  WidgetsFlutterBinding.ensureInitialized();

  // NEW: 1. connect to our Firebase project (settings from firebase_options).
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  debugPrint('Connected to Firebase: ${Firebase.app().options.projectId}');

  // NEW: 2. if someone was already signed in, load them BEFORE the first
  // frame, so a returning user never sees the login form flash.
  // appcontainer.read works here, before any widget exists.
  await appcontainer.read(accountProvider).restoreSession();

  runApp(const MyApp());
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  // This widget is the root of your application.
  @override
  Widget build(BuildContext context) {
    return UncontrolledProviderScope(
      container: appcontainer,
      child: MaterialApp(
        debugShowCheckedModeBanner: false,
        // HomePage now shows the login form or the profile.
        home: const HomePage(),
        routes: {
          "/home": (context) => const HomePage(),
          "/tasks": (context) => const TaskListPage(),
        },
      ),
    );
  }
}
